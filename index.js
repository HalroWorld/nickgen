export const types = Object.keys(nouns);

const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];

// region을 주면 그 지역 지명, 안 주면 형용사가 앞에 붙음
export function getRandomNickname(type = 'animals', region) {
  if (!nouns[type]) throw new Error(`unknown type: ${type} (${types.join(', ')})`);
  if (region && !places[region]) throw new Error(`unknown region: ${region} (${regions.join(', ')})`);
  const pool = region ? places[region] : adjectives;
  return `${pick(pool)} ${pick(nouns[type])}`;
}

